# Main
# =============================================================================

def main() -> None:
    p = argparse.ArgumentParser(formatter_class=argparse.RawDescriptionHelpFormatter,
                                description=__doc__)
    p.add_argument("--checkpoint",    type=Path, required=True,
                   help="encoder.pt from train.py (best-val checkpoint)")
    p.add_argument("--clusters-dir",  type=Path, required=True,
                   help="dir with clusters_NNNNNN.csv (for triplet sampling)")
    p.add_argument("--header-out",    type=Path,
                   default=Path("include/appearance_model_weights.hpp"))
    p.add_argument("--reference-csv", type=Path,
                   default=Path("tests/data/appearance_reference.csv"))
    p.add_argument("--triplets-csv",  type=Path,
                   default=Path("tests/data/appearance_triplets.csv"))
    p.add_argument("--n-triplets",    type=int, default=100)
    p.add_argument("--seed",          type=int, default=0)
    args = p.parse_args()

    # Load checkpoint. Whatever device the checkpoint was saved on, we
    # re-build the model on CPU here — the export is pure numpy IO.
    print(f"[export] loading {args.checkpoint}")
    ck = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
    feat_mean = np.asarray(ck["feat_mean"], dtype=np.float32)
    feat_std  = np.asarray(ck["feat_std"],  dtype=np.float32)
    model = AppearanceMLP(feat_mean, feat_std)
    model.load_state_dict(ck["state_dict"])
    model.eval()
    print(f"[export] best-val checkpoint: epoch {ck.get('epoch', '?')}, "
          f"val_acc {ck.get('val_accuracy', float('nan')):.4f}, "
          f"τ {ck.get('val_threshold', float('nan')):.3f}")

    ckpt_meta = {"path": args.checkpoint,
                 "val_accuracy": ck.get("val_accuracy", float("nan"))}

    # 1) header (overwrites the placeholder)
    export_header(model, ckpt_meta, args.header_out)

    # 2) reference CSV (drives EncoderMatchesPyTorchReference)
    export_reference_csv(model, args.reference_csv, seed=args.seed)

    # 3) triplets CSV (drives EmbeddingDistanceMonotoneOnAugmentation)
    export_triplets_csv(args.triplets_csv, args.clusters_dir,
                        args.n_triplets, seed=args.seed)

    print()
    print("[export] DONE.")
    print("[export] next steps on the C++ side:")
    print("  colcon build --packages-select construction_perception")
    print("  # remove GTEST_SKIP from the two gated tests in")
    print("  # tests/cpp/test_appearance_encoder.cpp")
    print("  ./build/construction_perception/test_appearance_encoder")


if __name__ == "__main__":
    main()
